#!/usr/bin/env python3
"""
Collects the user-visible text of every registered node type (label,
description, property labels/help/groups, palette subcategories, enum labels)
into conkystudio/i18n/_node_strings.py as QT_TRANSLATE_NOOP("Nodes", ...)
lines, so pylupdate6 can put them in the translation catalogs.

Node specs stay plain Qt-free data; the UI translates them at display time with
conkystudio.i18n.node_text(). The generated file is never imported by the app
and is not committed -- run conkystudio/tools/update_translations.sh instead of
calling this directly.

    python3 conkystudio/tools/i18n_node_strings.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

import conkystudio.nodes  # noqa: E402,F401 -- populates the registry (no Qt)
from conkystudio.nodes import registry  # noqa: E402

OUT = REPO_ROOT / "conkystudio" / "i18n" / "_node_strings.py"


def _wanted(s) -> bool:
    return isinstance(s, str) and bool(re.search(r"[A-Za-z]", s))


def collect() -> list[str]:
    seen: dict[str, None] = {}

    def add(s):
        if _wanted(s):
            seen.setdefault(s, None)

    for spec in registry.all_specs():
        add(spec.label)
        add(spec.description)
        add(spec.subcategory)
        for p in spec.properties:
            add(p.label)
            add(p.help)
            add(p.group)
            # enum values are stored in projects/Lua; only their labels are shown
            for c in (p.choice_labels or p.choices or []):
                add(c)
    return list(seen)


def _lit(s: str) -> str:
    r = repr(s)
    if r.startswith("'") and '"' not in s:
        r = '"' + r[1:-1].replace("\\'", "'") + '"'
    return r


def main() -> int:
    strings = collect()
    lines = [
        "# Generated by conkystudio/tools/i18n_node_strings.py -- do not edit, do not commit.",
        "# Read only by pylupdate6; the app never imports it.",
        "from PyQt6.QtCore import QT_TRANSLATE_NOOP",
        "",
    ]
    lines += [f'QT_TRANSLATE_NOOP("Nodes", {_lit(s)})' for s in strings]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(REPO_ROOT)}: {len(strings)} node strings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
