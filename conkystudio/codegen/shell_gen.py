"""
Data-source node properties -> polling shell scripts.

Every generated script here is dual-mode, controlled by an optional
`--key NAME` argument:

  script.sh --key cpu_temp    execi mode: computes everything, prints
                               ONLY that one value to stdout, does no
                               file I/O. What ${execi N script.sh --key
                               cpu_temp} calls.

  script.sh                   daemon mode: computes everything, then
                               writes the full flock-guarded, atomically-
                               replaced key=value cache file -- exactly
                               sensors.sh / weather.sh's own pattern.
                               What start.sh's background polling loop
                               calls.

One script per script_family (see nodes.registry.NodeSpec.script_family),
built once from whichever node in that family the project actually has
(if two nodes in the same family disagree on an override like the AMD
DRM card, the first one wins -- Conky Studio doesn't currently surface
that as a conflict warning, which is a fair thing to improve later).
"""
from __future__ import annotations

from conkystudio.model.project import Project
from conkystudio.nodes import registry

_SHEBANG_HEADER = "#!/usr/bin/env bash\n# Generated by Conky Studio -- adapted from sensors.sh / weather.sh.\nset -o pipefail\n\n"


def _sh_sq(value) -> str:
    """POSIX-safe single-quoted shell literal for splicing an arbitrary
    (possibly quote-containing) user-editable value into a generated
    script as one shell word: close the quote, emit an escaped literal
    quote, reopen the quote. Every free-text node property that ends up
    inside one of these heredocs (chip_pattern regex, AMD card override,
    disk device path, weather fallback location, player name, album-art
    fallback path) MUST go through this -- an un-escaped `'` or `"` in
    any of them is exactly what turns into a shell "Unterminated quoted
    string" error at runtime instead of a build-time failure, since none
    of these are validated against shell metacharacters when the user
    types them into the Properties panel."""
    s = "" if value is None else str(value)
    return "'" + s.replace("'", "'\\''") + "'"


_CACHE_DIR_BOILERPLATE = '''SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CACHE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)/.runtime-cache"
CACHE_FILE="${CACHE_DIR}/%(family)s.cache"
TMP_FILE="${CACHE_FILE}.tmp"

PRINT_KEY=""
if [[ "$1" == "--key" ]]; then PRINT_KEY="$2"; fi
'''


def _atomic_write_footer(family: str, kv_lines: str, print_case: str) -> str:
    return f'''
if [[ -n "$PRINT_KEY" ]]; then
    case "$PRINT_KEY" in
{print_case}
        *) echo "" ;;
    esac
    exit 0
fi

mkdir -p "$CACHE_DIR"
exec 200>"${{CACHE_DIR}}/.{family}.lock"
flock -w 5 200 || exit 0
{{
    echo "updated=$(date +%s)"
{kv_lines}
}} > "$TMP_FILE" && mv "$TMP_FILE" "$CACHE_FILE"
'''


def _first_node_props(project: Project, family: str) -> dict:
    for n in project.nodes:
        spec = registry.get(n.type)
        if spec.script_family == family:
            return n.props
    return {}


# --------------------------------------------------------------- CPU sensors
def gen_cpu_sensors_script(project: Project) -> str:
    props = _first_node_props(project, "cpu_sensors")
    chip_pattern = props.get("chip_pattern", "^(coretemp-|k10temp-|cpu_thermal-|zenpower-)")

    body = f'''
CPU_TEMP_CHIP_PATTERN={_sh_sq(chip_pattern)}

CPU_TEMP=""
if command -v sensors >/dev/null 2>&1; then
    CPU_TEMP="$(sensors -u 2>/dev/null | awk -v pat="$CPU_TEMP_CHIP_PATTERN" '
        $0 ~ pat {{ inchip=1; next }}
        inchip && /^$/ {{ inchip=0 }}
        inchip && /temp[0-9]+_input/ {{ print $2; exit }}
    ')"
fi
'''
    footer = _atomic_write_footer(
        "cpu_sensors",
        '    echo "cpu_temp=${CPU_TEMP:-}"',
        '        cpu_temp) echo "${CPU_TEMP:-0}" ;;',
    )
    return _SHEBANG_HEADER + (_CACHE_DIR_BOILERPLATE % {"family": "cpu_sensors"}) + body + footer


# --------------------------------------------------------------- GPU stats
def gen_gpu_stats_script(project: Project) -> str:
    props = _first_node_props(project, "gpu_stats")
    amd_card_override = props.get("amd_drm_card", "")

    body = f'''
GPU_DRM_CARD={_sh_sq(amd_card_override)}

GPU_STATUS="none"
GPU_UTIL=""; GPU_TEMP=""; GPU_VRAM_USED=""; GPU_VRAM_TOTAL=""

# Conky's own launch context sometimes has a more restricted PATH than an
# interactive shell even when nvidia-smi is genuinely installed, so fall
# back to the usual install locations directly if the PATH lookup misses.
NVIDIA_SMI_BIN="$(command -v nvidia-smi 2>/dev/null)"
if [[ -z "$NVIDIA_SMI_BIN" ]]; then
    for cand in /usr/bin/nvidia-smi /usr/local/bin/nvidia-smi /opt/nvidia/bin/nvidia-smi; do
        [[ -x "$cand" ]] && NVIDIA_SMI_BIN="$cand" && break
    done
fi

if [[ -n "$NVIDIA_SMI_BIN" ]]; then
    GPU_LINE="$("$NVIDIA_SMI_BIN" --query-gpu=utilization.gpu,temperature.gpu,memory.used,memory.total \\
                --format=csv,noheader,nounits 2>/dev/null | head -n1)"
    if [[ "$GPU_LINE" =~ ^[0-9] ]]; then
        IFS=',' read -r GPU_UTIL GPU_TEMP GPU_VRAM_USED GPU_VRAM_TOTAL <<< "$GPU_LINE"
        GPU_UTIL="${{GPU_UTIL// /}}"; GPU_TEMP="${{GPU_TEMP// /}}"
        GPU_VRAM_USED="${{GPU_VRAM_USED// /}}"; GPU_VRAM_TOTAL="${{GPU_VRAM_TOTAL// /}}"
        GPU_STATUS="ok"
    fi
fi

if [[ "$GPU_STATUS" != "ok" ]]; then
    # AMD via sysfs. card0 isn't always the right GPU on a hybrid/multi-GPU
    # system -- override GPU_DRM_CARD above if auto-detection (first card
    # with a gpu_busy_percent file) picks the wrong one.
    CARD="$GPU_DRM_CARD"
    if [[ -z "$CARD" ]]; then
        for c in /sys/class/drm/card*/device/gpu_busy_percent; do
            [[ -f "$c" ]] || continue
            CARD="$(basename "$(dirname "$(dirname "$c")")")"
            break
        done
    fi
    if [[ -n "$CARD" && -f "/sys/class/drm/${{CARD}}/device/gpu_busy_percent" ]]; then
        GPU_UTIL="$(cat "/sys/class/drm/${{CARD}}/device/gpu_busy_percent" 2>/dev/null)"
        for hw in "/sys/class/drm/${{CARD}}/device/hwmon/hwmon"*/temp1_input; do
            [[ -f "$hw" ]] || continue
            GPU_TEMP="$(( $(cat "$hw") / 1000 ))"
            break
        done
        if [[ -f "/sys/class/drm/${{CARD}}/device/mem_info_vram_used" ]]; then
            GPU_VRAM_USED="$(( $(cat "/sys/class/drm/${{CARD}}/device/mem_info_vram_used") / 1048576 ))"
            GPU_VRAM_TOTAL="$(( $(cat "/sys/class/drm/${{CARD}}/device/mem_info_vram_total") / 1048576 ))"
        fi
        [[ -n "$GPU_UTIL" ]] && GPU_STATUS="ok"
    fi
fi
'''
    footer = _atomic_write_footer(
        "gpu_stats",
        '    echo "gpu_status=${GPU_STATUS}"\n'
        '    echo "gpu_util=${GPU_UTIL:-0}"\n'
        '    echo "gpu_temp=${GPU_TEMP:-0}"\n'
        '    echo "gpu_vram_used=${GPU_VRAM_USED:-0}"\n'
        '    echo "gpu_vram_total=${GPU_VRAM_TOTAL:-0}"',
        '        gpu_util) echo "${GPU_UTIL:-0}" ;;\n'
        '        gpu_temp) echo "${GPU_TEMP:-0}" ;;\n'
        '        gpu_vram_used) echo "${GPU_VRAM_USED:-0}" ;;\n'
        '        gpu_vram_total) echo "${GPU_VRAM_TOTAL:-0}" ;;',
    )
    return _SHEBANG_HEADER + (_CACHE_DIR_BOILERPLATE % {"family": "gpu_stats"}) + body + footer


