# --------------------------------------------------------------- Weather
def gen_weather_script(project: Project) -> str:
    props = _first_node_props(project, "weather")
    fallback = props.get("fallback_location", "")

    body = f'''
FALLBACK_LOCATION={_sh_sq(fallback)}
TIMEOUT=6
FORMAT='%l|%C|%t|%f|%h|%w|%p'

fetch() {{
    local location="$1"
    curl -fsS --max-time "$TIMEOUT" -A "curl" "wttr.in/${{location}}?format=${{FORMAT}}" 2>/dev/null
}}

looks_bad() {{
    local s="$1"
    [[ -z "$s" ]] && return 0
    [[ "$s" == *"Unknown location"* ]] && return 0
    [[ "$s" == *"ERROR"* ]] && return 0
    [[ "$s" == *"<html"* ]] && return 0
    return 1
}}

# Category derived from the condition text -- same case-statement logic
# as skyrim_weather.sh, so an Image/Icon or Weather Icon node can be
# driven by category without needing the flavor-text remapping.
categorize() {{
    local c
    c="$(tr '[:upper:]' '[:lower:]' <<< "$1")"
    case "$c" in
        *clear*|*sunny*) echo "clear" ;;
        *overcast*) echo "overcast" ;;
        *partly*cloud*|*mostly*cloud*|*mostly*sunny*|*cloud*) echo "cloud" ;;
        *freezing*fog*|*mist*|*haze*|*fog*) echo "fog" ;;
        *wind*|*breez*|*gale*) echo "wind" ;;
        *heavy*rain*|*thunder*|*storm*) echo "storm" ;;
        *rain*|*drizzle*|*shower*) echo "rain" ;;
        *blizzard*|*heavy*snow*|*snow*|*sleet*|*ice*) echo "snow" ;;
        *frost*|*cold*) echo "cold" ;;
        *smoke*|*ash*|*dust*|*sand*) echo "dust" ;;
        *hot*) echo "hot" ;;
        *) echo "unknown" ;;
    esac
}}

RESULT="$(fetch "")"
if looks_bad "$RESULT" && [[ -n "$FALLBACK_LOCATION" ]]; then
    RESULT="$(fetch "$FALLBACK_LOCATION")"
fi

STATUS="fail"
CITY=""; COND=""; TEMP_F=""; FEELS=""; HUMID=""; WIND=""; PRECIP=""; CATEGORY="unknown"
if ! looks_bad "$RESULT"; then
    IFS='|' read -r CITY COND TEMP_F FEELS HUMID WIND PRECIP <<< "$RESULT"
    CATEGORY="$(categorize "$COND")"
    STATUS="ok"
fi
'''
    footer = _atomic_write_footer(
        "weather",
        '    echo "status=${STATUS}"\n'
        '    echo "city=${CITY}"\n'
        '    echo "condition=${COND}"\n'
        '    echo "category=${CATEGORY}"\n'
        '    echo "temp_f=${TEMP_F//[^0-9.-]/}"\n'
        '    echo "feels=${FEELS}"\n'
        '    echo "humidity=${HUMID}"\n'
        '    echo "wind=${WIND}"\n'
        '    echo "precip=${PRECIP}"',
        '        condition) echo "${COND:-Unknown}" ;;\n'
        '        category) echo "${CATEGORY:-unknown}" ;;\n'
        '        temp_f) echo "${TEMP_F//[^0-9.-]/}" ;;',
    )
    return _SHEBANG_HEADER + (_CACHE_DIR_BOILERPLATE % {"family": "weather"}) + body + footer


# --------------------------------------------------------------- Now Playing
def gen_nowplaying_script(project: Project) -> str:
    props = _first_node_props(project, "nowplaying")
    player = props.get("player", "spotify")

    body = f'''
PLAYER={_sh_sq(player)}

STATUS_RAW="$(playerctl -p "$PLAYER" status 2>/dev/null)"
STATUS="stopped"
TITLE=""; ARTIST=""; ALBUM=""; PROGRESS_PCT="0"

if [[ "$STATUS_RAW" == "Playing" || "$STATUS_RAW" == "Paused" ]]; then
    STATUS="$(tr '[:upper:]' '[:lower:]' <<< "$STATUS_RAW")"
    TITLE="$(playerctl -p "$PLAYER" metadata xesam:title 2>/dev/null)"
    ARTIST="$(playerctl -p "$PLAYER" metadata artist 2>/dev/null)"
    ALBUM="$(playerctl -p "$PLAYER" metadata album 2>/dev/null)"

    POS_US="$(playerctl -p "$PLAYER" metadata --format '{{{{position}}}}' 2>/dev/null)"
    LEN_US="$(playerctl -p "$PLAYER" metadata mpris:length 2>/dev/null)"
    if [[ -n "$POS_US" && -n "$LEN_US" && "$LEN_US" -gt 0 ]] 2>/dev/null; then
        PROGRESS_PCT="$(awk -v p="$POS_US" -v l="$LEN_US" 'BEGIN {{ printf "%.0f", (100 * p / l) }}')"
    fi
fi
'''
    footer = _atomic_write_footer(
        "nowplaying",
        '    echo "status=${STATUS}"\n'
        '    echo "title=${TITLE}"\n'
        '    echo "artist=${ARTIST}"\n'
        '    echo "album=${ALBUM}"\n'
        '    echo "progress_pct=${PROGRESS_PCT}"',
        '        status) echo "${STATUS}" ;;\n'
        '        title) echo "${TITLE}" ;;\n'
        '        artist) echo "${ARTIST}" ;;\n'
        '        album) echo "${ALBUM}" ;;\n'
        '        progress_pct) echo "${PROGRESS_PCT:-0}" ;;',
    )
    return _SHEBANG_HEADER + (_CACHE_DIR_BOILERPLATE % {"family": "nowplaying"}) + body + footer


# --------------------------------------------------------------- Album Art
def gen_album_art_script(node_id: str, player: str, fallback_path: str) -> str:
    """Per-instance (not family-shared, like Custom Script) -- adapted from
    fetch-art2.sh's streaming-art path (playerctl artUrl -> curl). The
    original's local-file ffmpeg-extraction branch isn't replicated here
    (an extra dependency for a narrower case); falls back to fallback_path
    instead when there's no streaming art URL to fetch."""
    out_name = f"album_art_{node_id}.png"
    fallback_line = f'FALLBACK={_sh_sq(fallback_path)}' if fallback_path else 'FALLBACK=""'
    return f'''#!/usr/bin/env bash
# Generated by Conky Studio -- simplified from fetch-art2.sh (streaming art only).
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
CACHE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)/.runtime-cache"
OUT_IMG="${{CACHE_DIR}}/{out_name}"
{fallback_line}
PLAYER={_sh_sq(player)}

mkdir -p "$CACHE_DIR"

STATUS="$(playerctl -p "$PLAYER" status 2>/dev/null)"
if [[ "$STATUS" != "Playing" && "$STATUS" != "Paused" ]]; then
    [[ -n "$FALLBACK" && -f "$FALLBACK" ]] && cp -f "$FALLBACK" "$OUT_IMG"
    exit 0
fi

ART_URL="$(playerctl -p "$PLAYER" metadata mpris:artUrl 2>/dev/null | sed 's;https://open.spotify.com;http://i.scdn.co;g')"
if [[ -z "$ART_URL" ]]; then
    [[ -n "$FALLBACK" && -f "$FALLBACK" ]] && cp -f "$FALLBACK" "$OUT_IMG"
    exit 0
fi

TMP_IMG="${{OUT_IMG}}.tmp"
if curl -fsS --max-time 4 "$ART_URL" -o "$TMP_IMG" && [[ -s "$TMP_IMG" ]]; then
    mv "$TMP_IMG" "$OUT_IMG"
else
    rm -f "$TMP_IMG"
    [[ -n "$FALLBACK" && -f "$FALLBACK" && ! -f "$OUT_IMG" ]] && cp -f "$FALLBACK" "$OUT_IMG"
fi
'''


# --------------------------------------------------------------- Custom script wrapper
def gen_custom_script_wrapper(node_id: str, inner_script_filename: str) -> str:
    """Wraps an arbitrary user script with the same daemon-mode cache
    harness, without needing to understand what the script does -- it
    just captures stdout as the single `value` key. In execi mode the
    inner script is called directly (see codegen/builder.py), so this
    wrapper is only generated/used for daemon-mode custom sources."""
    family = f"custom_{node_id}"
    body = f'''
INNER="$SCRIPT_DIR/{inner_script_filename}"
VALUE="$("$INNER" 2>/dev/null | head -n1)"
'''
    footer = _atomic_write_footer(
        family,
        '    echo "value=${VALUE}"',
        '        value) echo "${VALUE}" ;;',
    )
    return _SHEBANG_HEADER + (_CACHE_DIR_BOILERPLATE % {"family": family}) + body + footer
